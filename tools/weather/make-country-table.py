#!/usr/bin/env python3
"""Generate src/weather/countries.js: ISO 3166-1 numeric code -> alpha-2 (dev-time only).

Usage:  python3 tools/weather/make-country-table.py <path/to/iso_3166-1.json>   (the iso-codes package's file)

A national WIGOS station id is `0-{ISO 3166 numeric}-0-{local id}`; the table turns the numeric part into the country.
It is a standard code list, not station data.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
rows = json.load(open(sys.argv[1], encoding='utf-8'))['3166-1']
pairs = sorted((r['numeric'], r['alpha_2']) for r in rows)
body = ',\n'.join('  ' + ', '.join(f"'{n}': '{a}'" for n, a in pairs[i:i + 6]) for i in range(0, len(pairs), 6))
js = ("// Generated by tools/weather/make-country-table.py from the ISO 3166-1 code list. Do not edit by hand.\n"
      "// A national WIGOS station id is `0-{ISO 3166 numeric}-0-{local id}`: the numeric part names the issuing country.\n"
      f"export const ISO_NUMERIC_TO_ALPHA2 = Object.freeze({{\n{body}\n}});\n")
open(os.path.join(ROOT, 'src/weather/countries.js'), 'w', encoding='utf-8').write(js)
print(len(pairs), 'countries')
